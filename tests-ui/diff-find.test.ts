import { expect, test } from './fixtures'
import { git, write } from './repos'

test('diff find counts occurrences, wraps, preserves selection and does not move the code', async ({ open, small }) => {
  write(small, 'src/app.ts', "const repeated = 'needle needle'\n")
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  const diff = page.locator('.changes-diff .diff')
  await diff.locator('.dl.add .gutter').click()
  const bounds = await diff.boundingBox()
  await page.keyboard.press('Control+f')
  const input = page.getByRole('textbox', { name: 'Find in file' })
  await expect(input).toBeFocused()
  await input.fill('needle')
  await expect(page.locator('.find-bar-status')).toHaveText('1 of 2')
  await expect(diff.locator('.find-hit')).toHaveCount(2)
  expect(await diff.boundingBox()).toEqual(bounds)
  await page.keyboard.press('Enter')
  await expect(page.locator('.find-bar-status')).toHaveText('2 of 2')
  await page.keyboard.press('Enter')
  await expect(page.locator('.find-bar-status')).toHaveText('1 of 2')
  await page.keyboard.press('Shift+Enter')
  await expect(page.locator('.find-bar-status')).toHaveText('2 of 2')
  await input.fill('missing')
  await expect(page.locator('.find-bar-status')).toHaveText('No matches')
  await page.keyboard.press('Escape')
  await expect(input).toHaveCount(0)
  await expect(diff).toBeFocused()
  await expect(diff.locator('.picked')).toHaveCount(1)
  expect(git(small, 'diff', '--cached')).toBe('')
})

test('diff find visits both sides, uses source line numbers and survives a layout change', async ({ open, small }) => {
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  const diff = page.locator('.changes-diff .diff')
  await diff.locator('.dl.add .gutter').first().click()
  await page.keyboard.press('/')
  const input = page.getByRole('textbox', { name: 'Find in file' })
  await input.fill('const')
  const count = await page.locator('.find-bar-status').textContent()
  await diff.focus()
  await page.keyboard.press('Control+Shift+D')
  await expect(diff).toHaveClass(/side-mode/)
  await expect(input).toHaveValue('const')
  await expect(page.locator('.find-bar-status')).toHaveText(count!)
  await input.fill('value5 = 5')
  await expect(diff.locator('.dl.cursor')).toHaveAttribute('data-side', 'old')
  await input.fill('changed60')
  await expect(diff.locator('.dl.cursor')).toHaveAttribute('data-side', 'new')
  await expect(diff.locator('.dl.cursor')).toContainText('changed60')
  await input.fill(':60')
  await expect(page.locator('.find-bar-status')).toHaveText('Go to line 60')
  await page.keyboard.press('Enter')
  await expect(diff).toBeFocused()
  await expect(diff.locator('.dl.cursor')).toContainText('changed60')
  await page.keyboard.press('/')
  await input.fill(':30')
  await expect(page.locator('.find-bar-status')).toHaveText('Line not in diff')
  await input.fill('changed')
  await page.getByRole('button', { name: 'Next match', exact: true }).focus()
  await expect(page.getByRole('button', { name: 'Next match', exact: true })).toBeFocused()
  // The focused button's tooltip owns the first Escape; the next dismisses find.
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(input).toHaveCount(0)
  await expect(diff).toBeFocused()
})

test('diff find works in History file previews', async ({ open, small }) => {
  const page = await open(small, 'history')
  await page.locator('.commit-list').getByRole('option', { name: /Initial commit/ }).click()
  await page.locator('.details-files').getByText('app.ts', { exact: true }).click()
  const diff = page.locator('.details-diff .diff')
  await expect(diff).toContainText('value110')
  await diff.focus()
  await page.keyboard.press('/')
  const input = page.getByRole('textbox', { name: 'Find in file' })
  await input.fill('value110')
  await expect(page.locator('.find-bar-status')).toHaveText('1 of 1')
  await expect(diff.locator('.dl.cursor')).toContainText('value110')
  await expect(diff.locator('.dl.cursor')).toBeInViewport()
})

test('diff find keeps syntax and word highlights in light and dark', async ({ open, small }) => {
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  const diff = page.locator('.changes-diff .diff')
  await expect(diff.locator('.dl.add .code span[style*="color"]').first()).toBeVisible()
  await page.getByRole('button', { name: 'Find in file', exact: true }).click()
  await page.getByRole('textbox', { name: 'Find in file' }).fill('changed')
  await expect(diff.locator('.word-change.find-hit.current')).toHaveText('changed')
  for (const theme of ['light', 'dark']) {
    await page.evaluate((theme) => {
      document.documentElement.dataset.theme = theme
    }, theme)
    await expect(diff.locator('.find-hit.current[style*="color"]')).toBeVisible()
    await page.screenshot({ path: `out/diff-find-${theme}.png` })
  }
})

test('diff find reaches matches beyond truncation in a virtualized diff', async ({ open, hugeDiff }) => {
  const page = await open(hugeDiff)
  await page.getByRole('row', { name: /big\.ts/ }).click()
  const diff = page.locator('.changes-diff .diff')
  await expect(diff.locator('.dl').first()).toBeVisible()
  await diff.focus()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox', { name: 'Find in file' }).fill('edited60000')
  await expect(page.locator('.find-bar-status')).toHaveText('1 of 1')
  await expect(diff.locator('.dl.cursor')).toContainText('edited60000')
  await expect(diff.locator('.dl.cursor')).toBeInViewport()
  expect(await diff.locator('.dl').count()).toBeLessThan(300)
})
