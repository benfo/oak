import { expect, test } from './fixtures'
import { commitAll, git } from './repos'
import type { Page } from '@playwright/test'

async function compareCurrentBranchWithTarget(page: Page) {
  await page.keyboard.press('Control+Shift+p')
  await page.locator('.palette-input').fill('Compare current branch with…')
  await page.getByRole('option', { name: /Compare current branch with…/ }).click()
  const picker = page.locator('.palette-input')
  await expect(picker).toBeFocused()
  await picker.fill('target')
  await page.locator('.palette').getByRole('option').filter({ hasText: 'target' }).first().click()
}

test('Escape dismisses diff find and selection before restoring code, then keeps pane focus', async ({ open, small }) => {
  const page = await open(small)
  const file = page.getByRole('row', { name: /app\.ts/ })
  await file.click()
  const diff = page.locator('.changes-diff .diff')
  await diff.locator('.dl.add .gutter').first().click()
  await page.keyboard.press('F11')
  await page.keyboard.press('Control+f')
  const input = page.getByRole('textbox', { name: 'Find in file' })
  await input.fill('changed')
  await diff.focus()
  await page.keyboard.press('Escape')
  await expect(input).toHaveCount(0)
  await expect(diff.locator('.picked')).toHaveCount(1)
  await expect(file).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(diff.locator('.picked')).toHaveCount(0)
  await expect(file).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(file).toBeVisible()
  await diff.focus()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(diff).toBeFocused()
  await file.click()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(file).toBeFocused()
  expect(git(small, 'diff', '--cached')).toBe('')
})

test('Escape from Blame code closes find before restoring expanded code and preserves the view', async ({ open, small }) => {
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Show blame' }).click()
  const blame = page.locator('.blame-view .diff')
  await expect(page.locator('.blame-row').first()).toBeVisible()
  await expect(blame).toBeFocused()
  await page.keyboard.press('F11')
  await page.keyboard.press('Control+f')
  const input = page.getByRole('textbox', { name: 'Find in file' })
  await input.fill('const')
  await blame.focus()
  await page.keyboard.press('Escape')
  await expect(input).toHaveCount(0)
  await expect(page.locator('[data-workspace-layout]')).toHaveAttribute('data-workspace-layout', 'code')
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-workspace-layout]')).toHaveAttribute('data-workspace-layout', 'standard')
  await blame.focus()
  await page.keyboard.press('Escape')
  await expect(blame).toBeFocused()
  await expect(page.locator('.blame-view')).toBeVisible()
})

test('Escape exits comparison from its graph, preserves it in code, and exits file history the same way', async ({ open, small }) => {
  commitAll(small, 'Second commit')
  const page = await open(small, 'history')
  const graph = page.locator('.commit-list')
  await graph.getByRole('option', { name: /Second commit/ }).click()
  await graph.getByRole('option', { name: /Initial commit/ }).click({ modifiers: ['Control'] })
  const exit = page.getByRole('button', { name: 'Exit comparison', exact: true })
  await expect(exit).toBeVisible()
  await page.locator('.details-files').getByText('app.ts', { exact: true }).click()
  const diff = page.locator('.details-diff .diff')
  await expect(diff.locator('.dl').first()).toBeVisible()
  await diff.focus()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(exit).toBeVisible()
  await expect(diff).toBeFocused()
  await page.keyboard.press('F6')
  await expect(page.getByRole('toolbar', { name: 'Repository actions' }).locator(':focus')).toHaveCount(1)
  await page.keyboard.press('F6')
  await expect(page.locator('.sidebar').locator(':focus')).toHaveCount(1)
  await page.keyboard.press('F6')
  await expect(graph).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(exit).toHaveCount(0)
  await expect(graph).toBeFocused()
  await graph.getByRole('option', { name: /Second commit/ }).click()
  await graph.getByRole('option', { name: /Initial commit/ }).click({ modifiers: ['Control'] })
  await expect(exit).toBeVisible()
  await exit.focus()
  await page.keyboard.press('Escape')
  await expect(exit).toHaveCount(0)
  await expect(graph).toBeFocused()
  await graph.getByRole('option', { name: /Second commit/ }).click()
  await page.locator('.details-files').getByText('app.ts', { exact: true }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Show file history', exact: true }).click()
  const all = page.getByRole('button', { name: 'Show all commits', exact: true })
  await expect(all).toBeVisible()
  await graph.focus()
  await page.keyboard.press('Escape')
  await expect(all).toHaveCount(0)
  await expect(graph).toBeFocused()
  await page.locator('.details-files').getByText('app.ts', { exact: true }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Show file history', exact: true }).click()
  await expect(all).toBeVisible()
  await expect(graph).toBeFocused()
  await all.focus()
  await page.keyboard.press('Escape')
  await expect(all).toHaveCount(0)
  await expect(graph).toBeFocused()
})

test('Escape clears the All files filter without backing out of the tree', async ({ open, small }) => {
  const page = await open(small, 'history')
  await page
    .locator('.commit-list')
    .getByRole('option', { name: /Initial commit/ })
    .click()
  await page.getByRole('button', { name: 'All files' }).click()
  const tree = page.getByRole('treegrid', { name: 'Files in this commit' })
  await tree.getByRole('row', { name: /README\.md/ }).click()
  await page.keyboard.press('Control+f')
  const input = page.getByRole('textbox', { name: 'Find file in this commit' })
  await input.fill('README')
  await page.keyboard.press('Escape')
  await expect(input).toHaveValue('README')
  await expect(tree).toContainText('README.md')
  await page.keyboard.press('Escape')
  await expect(input).toHaveValue('')
  await page.keyboard.press('Escape')
  await expect(tree.locator(':focus')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'All files' })).toHaveAttribute('aria-pressed', 'true')
})

test('comparison banner Escape dismisses its tooltip or target picker before exiting', async ({ open, small }) => {
  git(small, 'branch', 'target')
  commitAll(small, 'Second commit')
  const page = await open(small, 'history')
  const graph = page.locator('.commit-list')
  await expect(graph.getByRole('option', { name: /Second commit/ })).toBeVisible()
  await graph.focus()
  await compareCurrentBranchWithTarget(page)
  const banner = page.locator('.comparison-banner')
  const exit = banner.getByRole('button', { name: 'Exit comparison', exact: true })
  await expect(exit).toBeVisible()
  const controls = page.getByRole('toolbar', { name: 'Branch comparison' })
  const target = controls.getByRole('button', { name: /^Change comparison target:/ })
  await expect(target).toBeVisible()
  await controls.getByRole('button', { name: 'Exit comparison', exact: true }).focus()
  await target.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.palette.dropdown .palette-input')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('.palette.dropdown')).toHaveCount(0)
  await expect(exit).toBeVisible()
  await expect(target).toBeFocused()
  await graph.focus()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(exit).toBeVisible()
  await exit.focus()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(exit).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(banner).toHaveCount(0)
  await expect(graph).toBeFocused()
})

test('F6 reaches an empty comparison result so Escape can exit it', async ({ open, small }) => {
  git(small, 'branch', 'target')
  const page = await open(small, 'history')
  await expect(page.locator('.commit-list')).toBeVisible()
  await page.locator('.commit-list').focus()
  await compareCurrentBranchWithTarget(page)
  const empty = page.locator('.history-empty')
  await expect(empty).toBeVisible()
  await page.getByRole('button', { name: 'Preferences', exact: true }).focus()
  await page.keyboard.press('F6')
  await expect(page.locator('.sidebar').locator(':focus')).toHaveCount(1)
  await page.keyboard.press('F6')
  await expect(empty).toBeFocused()
  await expect(empty).toHaveAttribute('data-focus-ring', '')
  expect(await empty.evaluate((el) => getComputedStyle(el.parentElement!, '::after').content)).toBe('""')
  await page.keyboard.press('Escape')
  await expect(page.locator('.comparison-banner')).toHaveCount(0)
})
