import { expect, test } from './fixtures'

test('shortcut search distinguishes modifiers and finds alternate widget keys', async ({ open, small }) => {
  const page = await open(small)
  await page.keyboard.press('Control+/')
  const dialog = page.getByRole('dialog', { name: 'Keyboard shortcuts' })
  const input = dialog.getByRole('textbox', { name: 'Search shortcuts' })
  const rows = dialog.locator('.shortcut-row')
  await expect(input).toBeFocused()
  await input.fill('Ctrl+F')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Find in focused pane')
  await expect(rows).toContainText('In code, enter :120 to go to line 120.')
  await expect(dialog.getByRole('region', { name: 'View', exact: true })).toHaveCount(0)
  await expect(dialog.getByText('Fetch all remotes', { exact: true })).toHaveCount(0)
  await input.fill('Ctrl+Shift+F')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Fetch all remotes')
  await input.fill('Alt+ArrowDown')
  await expect(rows).toHaveCount(2)
  await expect(rows.nth(0)).toContainText('Diff: next change (hunk)')
  await expect(rows.nth(1)).toContainText('Blame: next commit block')
  await input.fill('Shift+Alt+Down')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Move the nearest divider')
  await input.fill('Ctrl+Comma')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Preferences')
  await input.fill(',')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Preferences')
  await input.fill('/')
  await expect(rows).toHaveCount(2)
})

test('shortcut help describes scope, keeps key labels concise and fits the dialog', async ({ open, small }) => {
  const page = await open(small)
  await page.keyboard.press('Control+/')
  const dialog = page.getByRole('dialog', { name: 'Keyboard shortcuts' })
  await expect(dialog.getByRole('textbox', { name: 'Search shortcuts' })).toBeFocused()
  const rows = dialog.locator('.shortcut-row')
  await expect(rows.filter({ hasText: 'Next / previous control' })).toContainText('Tab / Shift+Tab')
  await expect(rows.filter({ hasText: 'Commit-message field: commit' }).first()).toContainText('Ctrl+Enter')
  await expect(rows.filter({ hasText: 'Focus History commit list (graph)' })).toContainText('Ctrl+Shift+2')
  await expect(rows.filter({ hasText: 'Restore expanded code after dismissing overlays' })).toContainText('Esc')
  await expect(rows.filter({ hasText: 'Changed-file list or diff:' }).locator('kbd')).toHaveText('V')
  await expect(rows.filter({ hasText: 'open context menu' }).locator('kbd')).toHaveText('Shift+F10 / Menu')
  const overflow = await rows.evaluateAll((elements) => elements.filter((el) => el.scrollWidth > el.clientWidth).length)
  expect(overflow).toBe(0)
  const input = dialog.getByRole('textbox', { name: 'Search shortcuts' })
  await input.fill('commit message')
  await page.keyboard.press('Escape')
  await expect(input).toHaveValue('')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
