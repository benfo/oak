import { expect, test } from './fixtures'
import { commitAll, git, write } from './repos'
import type { Page } from '@playwright/test'

const before = 'start\n  const name = "Ben"\n  return 1\nend\n'
const after = 'start\n\tconst name="Ben" \n    return 2\nend\n'

async function option(page: Page, label: string) {
  await page.getByRole('button', { name: 'Diff options', exact: true }).click()
  await page
    .getByRole('menuitemcheckbox', { name: label, exact: true })
    .or(page.getByRole('menuitemradio', { name: label, exact: true }))
    .click()
  // Checkable menus can stay open so several display options can be adjusted together.
  if (await page.getByRole('menu', { name: 'Diff options', exact: true }).isVisible()) await page.keyboard.press('Escape')
}

test('ignore whitespace stages only visible code edits and leaves whitespace-only files listed', async ({ open, small }) => {
  write(small, 'src/app.ts', before)
  commitAll(small, 'Before formatting')
  write(small, 'src/app.ts', after)
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  const diff = page.locator('.changes-diff .diff')
  await expect(diff.locator('.dl.add')).toHaveCount(2)
  const bounds = await diff.boundingBox()
  await option(page, 'Ignore whitespace changes')
  await expect(diff.locator('.dl.add')).toHaveCount(1)
  await expect(diff.locator('.dl.del')).toHaveCount(1)
  expect(await diff.boundingBox()).toEqual(bounds)
  await expect(page.locator('.changes-diff .diff-filter')).toHaveText('Ignoring whitespace')
  await diff.locator('.dl.del .gutter').click()
  await diff.locator('.dl.add .gutter').click({ modifiers: ['Control'] })
  await page.keyboard.press('Enter')
  await expect.poll(() => git(small, 'show', ':src/app.ts')).toBe(before.replace('  return 1', '    return 2'))
  await expect(page.locator('.changes-diff')).toContainText('Only whitespace changes.')
  await expect(page.getByRole('row', { name: /app\.ts/ }).first()).toBeVisible()
  expect(git(small, 'diff')).toContain('+\tconst name="Ben" ')
  await page.locator('.diff-empty').getByRole('button', { name: 'Show whitespace changes', exact: true }).click()
  await expect(diff.locator('.dl.add')).toHaveCount(1)
  await expect(page.locator('.changes-diff .diff-filter')).toBeHidden()
  await expect(diff).toBeFocused()
})

test('diff options are shared with History, keep find and highlighting accurate, and reset at startup', async ({ open, small }) => {
  write(small, 'src/app.ts', before)
  commitAll(small, 'Before formatting')
  write(small, 'src/app.ts', after)
  commitAll(small, 'Code and whitespace')
  write(small, 'src/app.ts', after.replace('return 2', 'return 3'))
  const page = await open(small, 'history')
  const graph = page.locator('.commit-list')
  await expect(graph).toBeFocused()
  await graph.getByRole('option', { name: /Code and whitespace/ }).click()
  await page.locator('.details-files').getByText('app.ts', { exact: true }).click()
  const diff = page.locator('.details-diff .diff')
  await option(page, 'Ignore whitespace changes')
  await expect(diff.locator('.dl.add')).toHaveCount(1)
  await option(page, 'Side by side')
  await expect(diff).toHaveClass(/side-mode/)
  await option(page, 'Show spaces and tabs')
  await diff.focus()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox', { name: 'Find in file' }).fill('return')
  await expect(page.locator('.find-bar-status')).toHaveText('1 of 2')
  for (const theme of ['light', 'dark']) {
    await page.evaluate((theme) => {
      document.documentElement.dataset.theme = theme
    }, theme)
    await expect(diff.locator('.dl.add .code span[style*="color"]').first()).toBeVisible()
    await expect(diff.locator('.find-hit')).toHaveCount(2)
    await page.screenshot({ path: `out/ignore-whitespace-${theme}.png` })
  }
  await page.keyboard.press('Control+1')
  await page.getByRole('row', { name: /app\.ts/ }).click()
  await expect(page.locator('.changes-diff .diff-filter')).toBeVisible()
  const fresh = await open(small)
  await fresh.getByRole('row', { name: /app\.ts/ }).click()
  await expect(fresh.locator('.changes-diff .diff-filter')).toBeHidden()
})

test('diff review changes preserve the source cursor and toolbar bounds in a reformatted file', async ({ open, small }) => {
  const lines = Array.from({ length: 120 }, (_, i) => `const value${i} = ${i}`)
  write(small, 'src/app.ts', lines.join('\n') + '\n')
  commitAll(small, 'Before reformatting')
  write(small, 'src/app.ts', lines.map((line, i) => `  ${i === 60 ? 'const changed60 = 600' : line}`).join('\n') + '\n')
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  await option(page, 'Full file')
  const diff = page.locator('.changes-diff .diff')
  await diff.locator('.dl.add').filter({ hasText: 'changed60' }).locator('.gutter').click()
  const cursor = diff.locator('.dl.cursor')
  await expect(cursor).toContainText('changed60')
  const bounds = await diff.boundingBox()
  await option(page, 'Ignore whitespace changes')
  await expect(cursor).toHaveAttribute('data-new-line', '61')
  await expect(cursor).toBeInViewport()
  expect(await diff.boundingBox()).toEqual(bounds)
  await page.locator('.changes-diff .diff-filter').click()
  await expect(diff).toBeFocused()
  await expect(cursor).toHaveAttribute('data-new-line', '61')
  await expect(cursor).toBeInViewport()
  await page.setViewportSize({ width: 960, height: 720 })
  const toolbar = page.locator('.changes-diff .diff-title')
  const options = page.getByRole('button', { name: 'Diff options', exact: true })
  await expect(options).toBeInViewport()
  const fits = await toolbar.evaluate((el) => el.scrollWidth <= el.clientWidth)
  expect(fits).toBe(true)
  const compactBounds = await diff.boundingBox()
  await option(page, 'Ignore whitespace changes')
  await expect(page.locator('.changes-diff .diff-filter')).toBeVisible()
  expect(await diff.boundingBox()).toEqual(compactBounds)
  await expect(options).toBeInViewport()
})

test('whitespace filter keeps added blank lines visible and options work from the keyboard', async ({ open, small }) => {
  write(small, 'src/app.ts', before)
  commitAll(small, 'Before formatting')
  write(small, 'src/app.ts', before.replace('  const name', '\tconst name').replace('end\n', '\nend\n'))
  const page = await open(small)
  await page.getByRole('row', { name: /app\.ts/ }).click()
  const button = page.getByRole('button', { name: 'Diff options', exact: true })
  await button.focus()
  await page.keyboard.press('Enter')
  const menu = page.getByRole('menu', { name: 'Diff options', exact: true })
  await expect(menu.locator(':focus')).toHaveCount(1)
  const ignore = page.getByRole('menuitemcheckbox', { name: 'Ignore whitespace changes', exact: true })
  await ignore.focus()
  await page.keyboard.press('Enter')
  if (await menu.isVisible()) await page.keyboard.press('Escape')
  const diff = page.locator('.changes-diff .diff')
  await expect(diff.locator('.dl.add')).toHaveCount(1)
  await expect(diff.locator('.dl.del')).toHaveCount(0)
  await expect(button).toBeFocused()
  await diff.focus()
  await page.keyboard.press('Enter')
  await expect.poll(() => git(small, 'show', ':src/app.ts')).toBe(before.replace('end\n', '\nend\n'))
})
